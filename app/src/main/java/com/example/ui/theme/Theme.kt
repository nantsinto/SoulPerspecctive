private val DarkColorScheme = darkColorScheme(
    primary = CyanPrimary,
    onPrimary = ObsidianBg,
    primaryContainer = CyanContainer,
    onPrimaryContainer = CyanPrimary,
    secondary = MintSecondary,
    onSecondary = ObsidianBg,
    tertiary = CoralAccent,
    background = ObsidianBg,
    onBackground = TextPrimary,
    surface = SurfaceDark,
    onSurface = TextPrimary,
    surfaceVariant = SurfaceElevated,
    onSurfaceVariant = TextSecondary,
    outline = DividerDark
)

private val LightColorScheme = darkColorScheme(
    // Defaulting to deep dark for immersive music player experience
    primary = CyanPrimary,
    onPrimary = ObsidianBg,
    primaryContainer = CyanContainer,
    onPrimaryContainer = CyanPrimary,
    secondary = MintSecondary,
    onSecondary = ObsidianBg,
    tertiary = CoralAccent,
    background = ObsidianBg,
    onBackground = TextPrimary,
    surface = SurfaceDark,
    onSurface = TextPrimary,
    surfaceVariant = SurfaceElevated,
    onSurfaceVariant = TextSecondary,
    outline = DividerDark
)

@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = true, // Music players excel in deep sleek dark mode
    dynamicColor: Boolean = false, // Keep consistent Cyan signature theme
    content: @Composable () -> Unit
) {
    val colorScheme = DarkColorScheme
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            if (window != null) {
                window.statusBarColor = ObsidianBg.toArgb()
                window.navigationBarColor = ObsidianBg.toArgb()
                WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = false
                WindowCompat.getInsetsController(window, view).isAppearanceLightNavigationBars = false
            }
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
